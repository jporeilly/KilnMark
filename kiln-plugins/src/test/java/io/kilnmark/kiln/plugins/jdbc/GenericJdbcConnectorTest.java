    static Connector.WriteOptions options(String table, String mode, Map<String, Object> settings) {
        return new Connector.WriteOptions(table, mode, List.of(), null, settings, "urn:kilnmark:h2-lab:" + table);
    }

    RunResult write(SourceConfig s, Connector.WriteOptions o, Schema schema, List<Object[]> rows,
                    List<MetadataEvent> events) throws Exception {
        return Rows.run(Rows.source(schema, rows, 3), h2.connector().writer(s, o), events);
    }

    List<List<Object>> query(String sql) throws Exception {
        try (Connection c = h2.connect(); Statement s = c.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            List<List<Object>> out = new ArrayList<>();
            while (rs.next()) {
                List<Object> row = new ArrayList<>();
                for (int i = 1; i <= rs.getMetaData().getColumnCount(); i++) {
                    row.add(rs.getObject(i));
                }
                out.add(row);
            }
            return out;
        }
    }

