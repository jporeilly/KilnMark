    @Test
    void theDriverSettingOffersRegisteredDriversOnly() {
        Connector.Setting driver = h2.connector().settings().get(0);
        assertEquals("driver", driver.key());
        assertEquals(SettingSpec.Kind.CHOICE, driver.kind());
        assertEquals(List.of("h2"), driver.choices());
        assertEquals(List.of("driver", "url", "username", "properties", "schemas", "read_only"),
            h2.connector().settings().stream().map(Connector.Setting::key).toList());
        assertEquals(SettingSpec.Kind.TEXT, h2.connector().settings().get(1).kind(), "the URL is free text");
        assertEquals("true", h2.connector().settings().get(5).defaultValue(), "read-only unless turned off");

        Connector none = new GenericJdbcConnector();
        assertEquals(SettingSpec.Kind.TEXT, none.settings().get(0).kind(), "no choices to offer");
        assertTrue(none.settings().get(0).hint().contains("Settings, JDBC drivers"));
        assertTrue(none.validate(reader).stream().anyMatch(p -> p.startsWith("driver: No JDBC driver called h2")));
        assertTrue(h2.connector().adminOnly(), "only admins set up sources whose URL goes to a registered driver");
        assertFalse(h2.connector().runsRulesInDatabase());
        assertNull(h2.connector().driver(), "nothing pinned");
    }

    @Test
    void theUrlMustStartAsTheDriversDoAndTheDriverMustAcceptIt() throws Exception {
        assertEquals(List.of(), h2.connector().validate(reader));
        assertTrue(problems("jdbc:db2://db.example.com:50000/SALES").contains(
            "url: the driver h2 takes URLs starting jdbc:h2:, and this one does not"));
        assertTrue(problems("https://db.example.com").get(0).startsWith("url: a JDBC URL, starting jdbc:"));
        assertTrue(problems(h2.url() + ";PASSWORD=secret").get(0).contains("would hold a user name or secret"));
        assertTrue(problems("jdbc:h2:tcp://kilnmark:secret@db.example.com/x").get(0)
            .startsWith("url: take the user name and password out"));
        assertTrue(problems(h2.url() + ";socketFactory=x.Y").get(0).contains("not registered to take the property "
            + "socketFactory"));
        assertTrue(problems(h2.url() + ";INIT=RUNSCRIPT").get(0).contains("not registered to take the property INIT"));
        assertTrue(problems(h2.url() + ";INIT=RUNSCRIPT FROM 'http://files.example.com/x.sql'").get(0)
            .contains("cannot read the settings in this URL"));
        assertTrue(problems("jdbc:h2:mem:x\nother").get(0).contains("a space or control character"));
        assertTrue(problems(h2.url() + ";MODE=DB2").isEmpty(), "an allowed property");
        assertFalse(problems(h2.url() + ";INIT=x").get(0).contains(h2.url()), "the URL is never echoed");

        // registered with a prefix the driver itself does not take: the driver's own answer counts
        H2Drivers.H2 odd = H2Drivers.registered("jdbc:hx:");
        SourceConfig s = new SourceConfig("odd", "jdbc", Map.of("driver", "h2", "url", "jdbc:hx:tcp://localhost/mem:x"),
            null);
        assertTrue(odd.connector().validate(s).contains("url: the driver h2 does not accept this URL. Check it "
            + "against the driver's documentation"), odd.connector().validate(s).toString());
    }

    private List<String> problems(String url) {
        return h2.connector().validate(h2.source("p", Map.of("url", url)));
    }

