    @Test
    void appendChecksEveryValueAgainstTheColumnsSizes() throws Exception {
        Schema s = new Schema(List.of(field("customer_id", Rows.INT64), field("total", Rows.decimal(12, 4)),
            field("note", Rows.TEXT), field("at_s", Rows.TIMESTAMP), field("small_n", Rows.INT16),
            field("raw", Rows.BINARY)));
        LocalDateTime whole = LocalDateTime.of(2024, 1, 1, 10, 0, 0);
        RunResult ok = write(writer, options("SALES.LEDGER", "append", Map.of()), s, Rows.list(
            new Object[] {1L, new BigDecimal("1234.5000"), "short", whole, (short) 100, new byte[] {1, 2}}),
            Rows.events());
        assertTrue(ok.succeeded(), ok.error());
        String[][] cases = {
            {"decimal", "the value 1.2345 in column TOTAL"},
            {"text", "the value in column NOTE is 8 characters long, but the column holds at most 5"},
            {"seconds", "column AT_S has more digits of a second than the column keeps (0)"},
            {"tiny", "the value 300 is outside -128 to 127"},
            {"bytes", "it is 3 bytes long, but the column holds at most 2"}};
        for (String[] c : cases) {
            Object[] row = {2L, BigDecimal.ONE, "short", whole, (short) 1, new byte[] {1}};
            switch (c[0]) {
                case "decimal" -> row[1] = new BigDecimal("1.2345");
                case "text" -> row[2] = "too long";
                case "seconds" -> row[3] = whole.plusNanos(500_000_000);
                case "tiny" -> row[4] = (short) 300;
                default -> row[5] = new byte[] {1, 2, 3};
            }
            RunResult r = write(writer, options("SALES.LEDGER", "append", Map.of()), s, Rows.list(row), Rows.events());
            assertFalse(r.succeeded(), c[0]);
            assertTrue(r.error().contains(c[1]), c[0] + ": " + r.error());
        }
        assertEquals(List.of(List.of(1L)), query("SELECT COUNT(*) FROM sales.ledger"));
    }

